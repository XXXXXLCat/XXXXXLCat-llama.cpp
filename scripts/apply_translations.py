def main():
    raw = open(JS, encoding='utf-8').read()
    # 现有键
    existing = set(re.findall(r"'([^'\\]*(?:\\.[^'\\]*)*)'\s*:", raw))
    new_items = {k: v for k, v in T.items() if k not in existing}
    print(f"现有键: {len(existing)}  本批翻译: {len(T)}  新增(去重后): {len(new_items)}")
    if not new_items:
        print("无需追加。")
        return
    lines = []
    lines.append('\n    // ===== 官方源码补全（批量，来自 llama.cpp WebUI 真实界面文本）=====')
    for k, v in new_items.items():
        # 转义单引号
        kk = k.replace("'", "\\'")
        vv = v.replace("'", "\\'")
        lines.append(f"    '{kk}': '{vv}',")
    block = '\n'.join(lines)
    # 在 DICT 结尾的 }; 之前插入
    marker = '  };'
    idx = raw.rfind(marker)
    if idx == -1:
        print("未找到 DICT 结尾标记，中止。")
        return
    out = raw[:idx] + block + '\n' + raw[idx:]
    open(JS, 'w', encoding='utf-8').write(out)
    print("已写入。新增条目示例：")
    for i, (k, v) in enumerate(list(new_items.items())[:5]):
        print(f"  {k!r} -> {v!r}")

if __name__ == '__main__':
    main()
